/** Converte texto importado (pt-BR) para pt-PT — corpo dos artigos. */
export function localizeBlogBody(text: string, postId?: string): string {
  let s = text
  const rules: [RegExp, string][] = [
    [/\bvocê\b/gi, 'si'],
    [/\bVocê\b/g, 'Si'],
    [/\bpara você\b/gi, 'para si'],
    [/\bpor você\b/gi, 'por si'],
    [/\bde você\b/gi, 'de si'],
    [/\bcom você\b/gi, 'consigo'],
    [/\bseus fios\b/gi, 'os seus fios'],
    [/\bseus cabelos\b/gi, 'os seus cabelos'],
    [/\bseu cabelo\b/gi, 'o seu cabelo'],
    [/\bseu couro cabeludo\b/gi, 'o seu couro cabeludo'],
    [/\bseu visual\b/gi, 'o seu visual'],
    [/\bsua rotina\b/gi, 'a sua rotina'],
    [/\bsua vida\b/gi, 'a sua vida'],
    [/\bsua saúde\b/gi, 'a sua saúde'],
    [/\bsua pele\b/gi, 'a sua pele'],
    [/\bsua casa\b/gi, 'a sua casa'],
    [/\bsua autoestima\b/gi, 'a sua autoestima'],
    [/\btransforme seus\b/gi, 'transforme os seus'],
    [/\btransforme suas\b/gi, 'transforme as suas'],
    [/\bseus pais\b/gi, 'os seus pais'],
    [/\bseus fios\b/gi, 'os seus fios'],
    [/\bte ajudar\b/gi, 'ajudar'],
    [/\bte ajuda\b/gi, 'ajuda'],
    [/\bincômodo\b/g, 'incómodo'],
    [/\bincômodos\b/g, 'incómodos'],
    [/\bestá fazendo\b/gi, 'está a fazer'],
    [/\bagendar horário\b/gi, 'marcar hora'],
    [/\bAgende seu\b/gi, 'Marque a sua'],
    [/\bHidrate seus\b/gi, 'Hidrate os seus'],
    [/\bLimpe seu\b/gi, 'Limpe o seu'],
    [/\bcontato\b/gi, 'contacto'],
    [/\bcelular\b/gi, 'telemóvel'],
    [/\bte dissesse\b/gi, 'lhe dissesse'],
    [/\bnossos\b/gi, 'os nossos'],
    [/\bnossas\b/gi, 'as nossas'],
    [/\bnosso\b/gi, 'o nosso'],
    [/\bnossa\b/gi, 'a nossa'],
    [/\bR\$\s*[\d.,]+/g, '—'],
    [/\bnão é mesmo\?\b/gi, 'não é verdade?'],
    [/\bPrepare-se\b/g, 'Prepare-se'],
    [/\bPrincipais Conclusões\b/g, 'Principais conclusões'],
    [/\bPerguntas frequentes\b/g, 'Perguntas frequentes'],
    [/\bPerguntas Frequentes\b/g, 'Perguntas frequentes'],
  ]
  for (const [re, repl] of rules) s = s.replace(re, repl)
  if (postId && blogBodyIntroPtPt[postId]) s = blogBodyIntroPtPt[postId](s)
  return s
}
